#!/usr/bin/env node
// Phase 12.1: builds docs/flutter-migration/PARITY_REPORT.md from PARITY_MATRIX.md.
// Rows are table lines with a tier (T1..T4) and a status in backticks. Run: node scripts/flutter-parity-report.mjs
import fs from 'node:fs';
import path from 'node:path';

const src = fs.readFileSync(path.resolve('docs/flutter-migration/PARITY_MATRIX.md'), 'utf8');
const rows = [];
for (const line of src.split('\n')) {
  if (!line.startsWith('| ')) continue;
  const c = line.split('|').slice(1, -1).map((x) => x.trim());
  if (c.length < 8 || !/^T[1-4]$/.test(c[4])) continue;
  const status = (c[6].match(/`([a-z]+)`/) || [])[1] || 'unknown';
  rows.push({ feature: c[0], flag: c[2].replace(/`/g, ''), pack: c[3].replace(/`/g, ''), tier: c[4], phase: c[5], status, note: c[6].replace(/`[a-z]+`\s*/, '') });
}
const tiers = ['T1', 'T2', 'T3', 'T4'];
const statuses = ['done', 'partial', 'deferred', 'todo'];
const count = (t, s) => rows.filter((r) => r.tier === t && r.status === s).length;

let out = `# Parity report (Phase 12.1)\n\nGenerated by \`node scripts/flutter-parity-report.mjs\` from \`PARITY_MATRIX.md\` (${rows.length} feature rows). Do not edit the tables by hand; edit the matrix and regenerate. The sections at the bottom are written by hand.\n\n`;
out += `## Counts by tier and status\n\n| Tier | done | partial | deferred | todo | total |\n|------|------|---------|----------|------|-------|\n`;
for (const t of tiers) out += `| ${t} | ${statuses.map((s) => count(t, s)).join(' | ')} | ${rows.filter((r) => r.tier === t).length} |\n`;
out += `| **all** | ${statuses.map((s) => rows.filter((r) => r.status === s).length).join(' | ')} | ${rows.length} |\n\n`;
out += `Meaning: **done** = built and covered by tests (headless); **partial** = built, but a device or staging step is open; **deferred** = deliberately postponed (see BACKLOG.md); **todo** = not built.\n\n`;
for (const t of ['T1', 'T2']) {
  const open = rows.filter((r) => r.tier === t && r.status !== 'done');
  out += `## ${t} rows that are not \`done\` (${open.length}): need a fix or an owner sign-off\n\n| Feature | Flag | Status | Note |\n|---------|------|--------|------|\n`;
  for (const r of open) out += `| ${r.feature} | ${r.flag} | ${r.status} | ${r.note.replace(/\|/g, '/')} |\n`;
  out += '\n';
}
out += `## T3 and T4 rows not \`done\` (${rows.filter((r) => ['T3', 'T4'].includes(r.tier) && r.status !== 'done').length}): post-launch / labs\n\n`;
for (const r of rows.filter((r) => ['T3', 'T4'].includes(r.tier) && r.status !== 'done')) out += `- ${r.tier} ${r.feature} (${r.flag}): ${r.status}\n`;
out += '\n';
const notesPath = path.resolve('docs/flutter-migration/PARITY_REPORT_NOTES.md');
if (fs.existsSync(notesPath)) out += fs.readFileSync(notesPath, 'utf8');
fs.writeFileSync(path.resolve('docs/flutter-migration/PARITY_REPORT.md'), out);
console.log(`PARITY_REPORT.md written: ${rows.length} rows`);
